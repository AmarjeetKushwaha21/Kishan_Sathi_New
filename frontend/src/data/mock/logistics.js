export function estimateFare(vehicle, km, quantity) {
  const base = vehicle.baseFare;
  const distance = Math.round(vehicle.ratePerKm * km);
  const over = quantity > vehicle.capacity ? (quantity - vehicle.capacity) * 3 : 0;
  return base + distance + over;
}

